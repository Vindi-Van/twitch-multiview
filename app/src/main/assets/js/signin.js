// Signing in. Step 1 shows a code (and QR) for twitch.tv/activate; the app polls Twitch until it's
// approved (OAuth device flow, see TwitchAccount.kt). Step 2 offers Twitch's own sign-in page, so the
// embedded players and chat know who you are.

import { native } from './bridge.js';
import { DIRECTIONS } from './config.js';
import { $, h } from './dom.js';
import { focusables, focused, moveFocus, setFocus } from './focus.js';
import { clearResults, startPlayerSignIn } from './picker.js';
import { go, register } from './screens.js';
import { refreshAccount, state } from './state.js';

let countdownTimer = 0;

function enter() {
  if (!state.account.signInAvailable) return renderUnavailable();
  renderCode({ state: 'starting' });
  native.send('signIn');
}

function leave() {
  clearInterval(countdownTimer);
  native.send('cancelSignIn');
}

native.on('signin', async (e) => {
  if (state.screen !== 'signin') return;
  if (e.state !== 'done') return renderCode(e);
  await refreshAccount();
  clearResults();
  renderPlayerStep();
});

const brand = () => h('div', { class: 'brand', text: 'Multiview' });
const button = (key, action, text, primary = false) => h('button', { class: `btn${primary ? ' primary' : ''} focusable`, data: { key, action }, text });

/** Step 1: the code to enter at twitch.tv/activate (or scan), and how long it has left. */
function renderCode(e) {
  clearInterval(countdownTimer);
  const status = h('span', { class: 'status' });
  const buttons = [];
  if (e.state === 'starting') {
    status.textContent = 'Getting a code…';
  } else if (e.state === 'code') {
    const until = Date.now() + e.expiresIn * 1000;
    const tick = () => {
      const left = Math.max(0, Math.round((until - Date.now()) / 1000));
      status.textContent = `Waiting for you · code expires in ${Math.floor(left / 60)}:${String(left % 60).padStart(2, '0')}`;
    };
    tick();
    countdownTimer = setInterval(tick, 1000);
  } else {
    status.textContent = e.state === 'expired' ? 'That code expired.' : `Couldn't reach Twitch (${e.message}).`;
    buttons.push(button('si:again', 'again', 'Get a new code', true));
  }
  buttons.push(button('si:skip', 'skip', 'Skip for now'));

  const qr = h('div', { class: 'qr', role: 'img', 'aria-label': 'QR code that opens twitch.tv/activate with the code filled in' });
  if (e.state === 'code' && globalThis.qrcode) {
    const code = globalThis.qrcode(0, 'M');
    code.addData(e.uri);
    code.make();
    qr.innerHTML = code.createSvgTag({ cellSize: 8, margin: 0, scalable: true });  // generated by the QR library from Twitch's URL
  }

  $('#signin').replaceChildren(
    brand(),
    h('div', { class: 'body' },
      h('div', { class: 'text' },
        h('div', {}, h('div', { class: 'step', text: 'Step 1 of 2' }), h('h1', { text: 'Connect your Twitch account' }),
          h('p', { class: 'lead', text: 'Use your phone. Nothing to type on the TV.' })),
        h('ol', {},
          h('li', {}, h('span', { class: 'num', text: '1' }), h('span', { class: 'what' }, 'On your phone or computer, go to', h('span', { class: 'url', text: 'twitch.tv/activate' }))),
          h('li', {}, h('span', { class: 'num', text: '2' }), h('span', { class: 'what' }, 'Enter this code', h('span', { class: 'code', text: e.state === 'code' ? e.userCode : '········' }))),
          h('li', {}, h('span', { class: 'num', text: '3' }), h('span', { class: 'what', text: 'Approve Multiview. This screen moves on by itself.' }))),
        status,
        h('div', { class: 'actions' }, buttons)),
      e.state === 'code' ? h('figure', {}, qr, h('figcaption', { text: 'Or scan this: it opens the page with the code filled in' })) : null),
    h('p', { class: 'foot', text: 'This lets Multiview see who you follow and search Twitch. Skip it and you type channel names instead.' }));
  setFocus(focusables($('#signin'))[0]);
}

/** Step 2: Twitch's own sign-in page, so the players and chat know who you are. */
function renderPlayerStep() {
  clearInterval(countdownTimer);
  $('#signin').replaceChildren(
    brand(),
    h('div', { class: 'body' },
      h('div', { class: 'text' },
        h('div', {}, h('div', { class: 'step', text: `Step 2 of 2 · signed in as ${state.account.login}` }),
          h('h1', { text: 'Sign in to the video player' }),
          h('p', { class: 'lead', text: "The players only know you're signed in through twitch.tv itself, so this is a second, one-time sign-in." })),
        h('ul', { class: 'benefits' },
          h('li', { text: 'No ads with Turbo, or on channels you subscribe to' }),
          h('li', { text: 'Chat shows your badges and emotes' })),
        h('p', { class: 'lead', text: "It opens Twitch's own sign-in page: up and down move between boxes, OK opens the keyboard. Multiview never sees your password." }),
        h('div', { class: 'actions' },
          button('si:player', 'player', "Open Twitch's sign-in page", true),
          button('si:skip', 'skip', 'Skip, watch with ads')))));
  setFocus($('#signin [data-key="si:player"]'));
}

/** A build without a Twitch Client ID can't sign in; say so and carry on without an account. */
function renderUnavailable() {
  $('#signin').replaceChildren(
    brand(),
    h('div', { class: 'body' },
      h('div', { class: 'text' },
        h('div', {}, h('h1', { text: "Sign-in isn't set up in this build" }),
          h('p', { class: 'lead', text: "This copy of Multiview was built without a Twitch Client ID, so it can't show who you follow or search Twitch. You can still add channels by typing their names." }),
          h('p', { class: 'lead', text: 'Built it yourself? Add twitch.clientId to local.properties and rebuild (see the README).' })),
        h('div', { class: 'actions' }, button('si:skip', 'skip', 'Continue', true)))));
  setFocus($('#signin [data-key="si:skip"]'));
}

function key(name) {
  if (DIRECTIONS.includes(name)) {
    moveFocus(focusables($('#signin')), name);
    return;
  }
  const action = (name === 'ok' || name === 'hold') ? focused()?.dataset.action : name === 'back' ? 'skip' : null;
  if (action === 'again') enter();
  else if (action === 'player') startPlayerSignIn('following');
  else if (action === 'skip') go('picker', state.account.userId ? 'following' : 'search');
}

register('signin', { enter, leave, key });
