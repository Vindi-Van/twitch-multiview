/**
 * Builds an element: h('div', { class, text, data, style, ...attributes }, ...children).
 * Null, undefined and false children are skipped; strings become text nodes.
 */
export function h(tag, props = {}, ...children) {
  const el = document.createElement(tag);
  for (const [key, value] of Object.entries(props)) {
    if (value == null || value === false) continue;
    if (key === 'class') el.className = value;
    else if (key === 'text') el.textContent = value;
    else if (key === 'data') Object.assign(el.dataset, value);
    else if (key === 'style') Object.assign(el.style, value);
    else el.setAttribute(key, value === true ? '' : value);
  }
  el.append(...children.flat().filter((child) => child != null && child !== false));
  return el;
}

/** One of the constant icons above (never markup from anywhere else). */
export function icon(name) {
  const el = h('span', { class: 'icon' });
  el.innerHTML = ICONS[name];
  return el;
}

/** Fills every `<span data-icon="name">` in the static HTML. */
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => { el.innerHTML = ICONS[el.dataset.icon]; });
}
